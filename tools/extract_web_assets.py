"""Generate browser assets directly from the PRG; no runtime fetch/build needed."""
import hashlib
import json
from pathlib import Path
from disassemble import load

memory, _, _ = load('tuttifrutti.prg')
assets = {
    'sourceSHA256': hashlib.sha256(Path('tuttifrutti.prg').read_bytes()).hexdigest(),
    'charset': list(memory[0x3800:0x4000]),
    'maps': [[n for b in memory[0x3500+i*96:0x3500+(i+1)*96]
              for n in [b >> 4, b & 15]] for i in range(7)],
    'apples': [[[memory[0x37a0+i*16+j], memory[0x37a0+i*16+8+j]]
                for j in range(6) if memory[0x37a0+i*16+j] != 255] for i in range(6)],
    'tiles': [[memory[base+i] for base in [0x1880,0x1888,0x1890,0x1898]] for i in range(8)],
    'tileColors': list(memory[0x18a0:0x18a8]),
    'rowColors': list(memory[0x34d0:0x34e8]),
    'figureStarts': list(memory[0x3e80:0x3e86]),
    'figureEnds': list(memory[0x3e86:0x3e8c]),
    'figureChars': list(memory[0x3e8c:0x3eaa]),
    'figureOffsets': list(memory[0x3eaa:0x3ec8]),
    'objectStarts': list(memory[0x3400:0x3408]),
    'objectEnds': list(memory[0x3408:0x3410]),
    'objectChars': list(memory[0x3410:0x343c]),
    'objectOffsets': list(memory[0x343c:0x3468]),
    'music': list(memory[0x3f00:0x3fc0]),
    'note1Low': list(memory[0x3fc0:0x3fd0]),
    'note1High': list(memory[0x3fd0:0x3fe0]),
    'note2Low': list(memory[0x3fe0:0x3ff0]),
    'note2High': list(memory[0x3ff0:0x4000]),
}
# The PRG ends at $3FFE; memory[$3FFF] is zero-filled, not original data.
text = '// Generated by tools/extract_web_assets.py from tuttifrutti.prg.\n'
text += '// Original graphics, maps and music: Shaun Southern / Mr. Chip Software, 1985.\n'
text += 'globalThis.Tutti = globalThis.Tutti || {};\n'
text += 'globalThis.Tutti.assets = ' + json.dumps(assets, separators=(',', ':')) + ';\n'
Path('web/assets.js').write_text(text)
print('Generated web/assets.js')
